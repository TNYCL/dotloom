#!/usr/bin/env node
// Generate THIRD-PARTY-NOTICES.md: the licenses of everything compiled into what
// Dotloom distributes — the engine/renderer WebAssembly in @dotloom/sdk and the CLI
// binaries of a GitHub Release — plus the embedded Inter font (OFL-1.1).
//
//   node scripts/third-party-notices.mjs          # write the file
//   node scripts/third-party-notices.mjs --check  # fail if it is out of date
//
// Crates are taken from `cargo metadata` (normal dependencies of the shipped
// crates, all platforms, all features); each crate's own license files are copied
// verbatim and identical texts are grouped.

import { spawnSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'THIRD-PARTY-NOTICES.md')
const SHIPPED = ['dotloom-wasm', 'dotloom-render-web', 'dotloom-cli']

const r = spawnSync('cargo', ['metadata', '--format-version', '1', '--locked', '--all-features'], {
  cwd: root,
  encoding: 'utf8',
  maxBuffer: 256 * 1024 * 1024,
})
if (r.status !== 0) {
  console.error(r.stderr)
  process.exit(1)
}
const meta = JSON.parse(r.stdout)
const byId = new Map(meta.packages.map((p) => [p.id, p]))
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]))
const workspace = new Set(meta.workspace_members)

// Normal (non-dev, non-build) dependency closure of the shipped crates.
const seen = new Set()
const queue = meta.packages.filter((p) => SHIPPED.includes(p.name) && workspace.has(p.id)).map((p) => p.id)
if (queue.length !== SHIPPED.length) {
  console.error(`shipped crates not found: ${SHIPPED.join(', ')}`)
  process.exit(1)
}
while (queue.length > 0) {
  const id = queue.pop()
  if (seen.has(id)) continue
  seen.add(id)
  for (const dep of nodes.get(id)?.deps ?? []) {
    if (dep.dep_kinds.some((k) => k.kind === null)) queue.push(dep.pkg)
  }
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice|copyright)([-._].*)?$/i
const crates = [...seen]
  .filter((id) => !workspace.has(id))
  .map((id) => byId.get(id))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))

// Group crates by identical license text.
const groups = new Map()
const missing = []
for (const c of crates) {
  const dir = dirname(c.manifest_path)
  const files = existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => LICENSE_FILE.test(f))
        .sort()
    : []
  if (files.length === 0) {
    missing.push(c)
    continue
  }
  for (const f of files) {
    const text = readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim()
    const g = groups.get(text) ?? { text, crates: [] }
    g.crates.push(`${c.name} ${c.version} (${c.license ?? 'see text'})`)
    groups.set(text, g)
  }
}

const ofl = readFileSync(join(root, 'crates/render/assets/OFL.txt'), 'utf8').replace(/\r\n/g, '\n').trim()
const lines = [
  '# Third-party notices',
  '',
  '<!-- Generated by scripts/third-party-notices.mjs; do not edit by hand. -->',
  '',
  'Dotloom is licensed under MIT OR Apache-2.0 (`LICENSE-MIT`, `LICENSE-APACHE`). The',
  'WebAssembly modules in `@dotloom/sdk` and the `dotloom` CLI binaries also contain the',
  'third-party software listed below. Each entry reproduces the license files the',
  'crate ships with.',
  '',
  '## Inter font (SIL Open Font License 1.1)',
  '',
  'A subset of Inter 4.1 (`crates/render/assets/Inter-Regular-subset.ttf`) is embedded',
  'in the renderer for text drawing.',
  '',
  '```text',
  ofl,
  '```',
  '',
  `## Rust crates (${crates.length})`,
  '',
]
for (const g of [...groups.values()].sort((a, b) => a.crates[0].localeCompare(b.crates[0]))) {
  lines.push(`### ${g.crates.join(', ')}`, '', '```text', g.text.replaceAll('```', "'''"), '```', '')
}
if (missing.length > 0) {
  lines.push('## Crates without a license file in their package', '')
  lines.push(
    'These crates declare their license only in `Cargo.toml`; the standard texts are at',
    'https://spdx.org/licenses/ (MIT, Apache-2.0 and Zlib).',
    '',
  )
  for (const c of missing) lines.push(`- ${c.name} ${c.version}: ${c.license ?? 'no license field'}`)
  lines.push('')
}
const text = `${lines.join('\n').trimEnd()}\n`

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : ''
  if (current !== text) {
    console.error('✖ THIRD-PARTY-NOTICES.md is out of date: run node scripts/third-party-notices.mjs')
    process.exit(1)
  }
  console.log(`✓ THIRD-PARTY-NOTICES.md is current (${crates.length} crates)`)
} else {
  writeFileSync(out, text)
  console.log(`wrote THIRD-PARTY-NOTICES.md (${crates.length} crates, ${groups.size} license texts)`)
}
