/** Text of a tool label or prompt key (`'tr…'` locales get Turkish, others English). */
export function toolText(key: string, locale = 'en'): string {
  const table: Record<string, string> = locale.toLowerCase().startsWith('tr') ? TOOL_MESSAGES_TR : TOOL_MESSAGES_EN
  return table[key] ?? key
}
