export const LOCALES: Record<string, Messages> = { en, tr }

export type Translate = (key: string, params?: Record<string, string | number>) => string

const I18nCtx = createContext<Translate>((k) => (en as Record<string, string>)[k] ?? k)

export function makeTranslate(locale: string, overrides: Partial<Record<string, string>> = {}): Translate {
  const base = LOCALES[locale] ?? LOCALES[locale.split('-')[0] ?? ''] ?? en
  return (key, params) => {
    const msg = overrides[key] ?? (base as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key
    return params ? msg.replace(/\{(\w+)\}/g, (_, n: string) => String(params[n] ?? `{${n}}`)) : msg
  }
}

export function I18nProvider(props: {
  locale?: string
  messages?: Partial<Record<string, string>>
  children: ReactNode
}): ReactNode {
  const t = useMemo(() => makeTranslate(props.locale ?? 'en', props.messages), [props.locale, props.messages])
  return <I18nCtx.Provider value={t}>{props.children}</I18nCtx.Provider>
}

/** Translation function of the nearest `I18nProvider`. */
export function useT(): Translate {
  return useContext(I18nCtx)
}
